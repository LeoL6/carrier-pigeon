  static SPIClass epdSPI(FSPI);

  // <===================>
  //   E-Paper SPI pins
  // <===================>
  static constexpr int PIN_SCK  = 36;
  static constexpr int PIN_MOSI = 45;
  static constexpr int PIN_MISO = -1;

  // <===================>
  //   E-Paper SPI pins
  // <===================>
  static constexpr int PIN_CS   = 26;
  static constexpr int PIN_DC   = 48;
  static constexpr int PIN_RST  = 47;
  static constexpr int PIN_BUSY = 34;

  // <===================>
  //   3.7'' EPD Module
  // <===================>
  static GxEPD2_BW<GxEPD2_370_GDEY037T03, GxEPD2_370_GDEY037T03::HEIGHT> display(GxEPD2_370_GDEY037T03(PIN_CS, PIN_DC, PIN_RST, PIN_BUSY));


  void init()
  {
    display.init(115200, true, 50, false);

    pinMode(PIN_BUSY, INPUT);
    pinMode(PIN_RST, OUTPUT);
    
    epdSPI.begin(PIN_SCK, PIN_MISO, PIN_MOSI, PIN_CS);

    // Bind SPI to display (recommended on ESP32-S3)
    display.epd2.selectSPI(
      epdSPI,
      SPISettings(4000000, MSBFIRST, SPI_MODE0)
    );
    
    display.setRotation(1);
  }

